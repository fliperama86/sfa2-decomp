#!/usr/bin/env python3
"""Seconds: sparse encoder/rejections and offline cipher byte wrapper, synthetic only."""
import ctypes as C
import hashlib
from pathlib import Path
import struct,subprocess,sys,tempfile,unittest
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'port/intro'))
import import_full as imp
class ImportControls(unittest.TestCase):
    def test_sparse_layout(self):
        pack=imp.encode([(1,80,b'xyz'),(0,40,b'abc')],[(0x08000003,bytes([15])*64)])
        self.assertEqual(pack[:8],b'SFA2I003');self.assertEqual(pack[8:40],hashlib.sha256(pack[40:]).digest())
        payload=pack[40:];self.assertEqual(struct.unpack_from('>II',payload),(2,1))
        self.assertEqual(struct.unpack_from('>IIII',payload,8),(0,40,3,52))
        self.assertEqual(struct.unpack_from('>IIII',payload,24),(1,80,3,55))
        self.assertEqual(struct.unpack_from('>III',payload,40),(0x08000003,64,58))
        self.assertEqual(payload[52:58],b'abcxyz')
    def test_refusals(self):
        tile=[(0x08000003,bytes(64))]
        for spans in [[],[(2,1,b'a')],[(0,0x300000,b'a')],[(0,2,b'abc'),(0,3,b'd')]]:
            with self.assertRaises(ValueError):imp.encode(spans,tile)
        for tiles in [[],[(0x10000003,bytes(256))],[(0x08000003,bytes([16])*64)],tile+tile]:
            with self.assertRaises(ValueError):imp.encode([(0,0,b'a')],tiles)
        with tempfile.TemporaryDirectory() as path:
            archive=Path(path)/'invalid.zip';archive.write_bytes(b'no game input')
            with self.assertRaisesRegex(ValueError,'unsupported arcade'):imp.archive_inputs(archive)
        with self.assertRaisesRegex(ValueError,'private assets'):imp.private_output(ROOT/'port/intro/wrong.dat')
    def test_probe_bookkeeping(self):
        with tempfile.TemporaryDirectory(prefix='intro-probe-') as directory:
            binary=Path(directory)/'probe.so'
            subprocess.run(['cc','-std=c11','-O2','-Wall','-Wextra','-Werror','-shared','-fPIC',*[str(ROOT/x) for x in ['port/intro/tools/import_probe.c','port/intro/resources.c','port/intro/tests/import_probe_stub.c']],'-o',str(binary)],check=True,timeout=20)
            dll=C.CDLL(str(binary));dll.intro_probe_start.argtypes=[C.c_void_p,C.c_size_t,C.c_void_p,C.c_size_t,C.c_void_p,C.c_size_t,C.c_uint]
            dll.intro_probe_reads.argtypes=[C.c_uint];dll.intro_probe_reads.restype=C.c_void_p
            dll.intro_probe_tile.argtypes=[C.c_uint,C.POINTER(C.c_uint32)];dll.intro_probe_tile.restype=C.c_void_p
            dll.intro_probe_error.restype=C.c_char_p;dll.intro_probe_frame_hash.restype=C.c_uint64
            dll.intro_probe_packed_start.argtypes=[C.c_void_p,C.c_size_t,C.c_uint]
            planes=[C.create_string_buffer(0x300000) for _ in range(2)];gfx=C.create_string_buffer(0x1400000)
            self.assertEqual(dll.intro_probe_start(planes[0],0x300000,planes[1],0x300000,gfx,0x1400000,7),0)
            self.assertEqual(dll.intro_probe_start(None,0x300000,planes[1],0x300000,gfx,0x1400000,7),-1)
            full=imp.play(dll);self.assertEqual(len(full),2)
            for plane,start,n in [(0,10,5),(1,20,3)]:
                seen=C.string_at(dll.intro_probe_reads(plane),0x300000)
                self.assertEqual(seen.count(1),n);self.assertEqual(seen[start:start+n],bytes([1])*n)
            key=C.c_uint32();tiles=[]
            for slot in range(65536):
                ptr=dll.intro_probe_tile(slot,C.byref(key))
                if ptr:tiles.append((key.value,C.string_at(ptr,(key.value>>24)**2)))
            self.assertEqual(sorted(k for k,_ in tiles),[0x08000000,0x08000001,0x10000002,0x20000004])
            self.assertTrue(all(not any(p) for _,p in tiles))
            pack=imp.encode([(0,10,bytes(5)),(1,20,bytes(3))],tiles);payload=C.create_string_buffer(pack[40:])
            self.assertEqual(dll.intro_probe_packed_start(payload,len(pack)-40,7),0);self.assertEqual(imp.play(dll),full)
    def test_closure_budget(self):
        class Incomplete:
            def intro_probe_step(self):return 0
            def intro_probe_error(self):return None
            def intro_probe_frame_hash(self):return 0
        with self.assertRaisesRegex(ValueError,'bounded update'):imp.play(Incomplete())
    def test_cipher_wrapper(self):
        # Golden digest from the pinned upstream implementation's standalone
        # adapter, on this generated byte ramp/key. No game bytes or key.
        with tempfile.TemporaryDirectory(prefix='intro-cipher-') as directory:
            binary=Path(directory)/'cipher.so';folder=ROOT/'port/intro/tools/cps2crypt'
            subprocess.run(['c++','-std=c++17','-O2','-Wall','-Wextra','-Werror','-Wno-sign-compare','-shared','-fPIC',str(folder/'cps2crypt.cpp'),str(folder/'decrypt.cpp'),'-o',str(binary)],check=True,timeout=20)
            dll=C.CDLL(str(binary));dll.intro_import_decrypt.argtypes=[C.c_void_p,C.c_size_t,C.c_void_p,C.c_size_t,C.c_void_p]
            source=C.create_string_buffer(bytes(range(256))*12288);key=C.create_string_buffer(bytes(range(20)));out=C.create_string_buffer(0x300000)
            self.assertEqual(dll.intro_import_decrypt(source,0x300000,key,20,out),0)
            self.assertEqual(hashlib.sha256(out.raw).hexdigest(),'87952881feb7aea913fe8f056a7a62518665e0df7e655176880ebac6c30ab08c')
            before=out.raw
            self.assertEqual(dll.intro_import_decrypt(source,0x300000,key,19,out),-1);self.assertEqual(out.raw,before)
            self.assertEqual(dll.intro_import_decrypt(source,0x300002,key,20,out),-1)
            self.assertEqual(dll.intro_import_decrypt(None,0x300000,key,20,out),-1)
if __name__=='__main__':unittest.main()

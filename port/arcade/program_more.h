/* More of the PS1 program's data built from the arcade set: the cell lists and position runs of the shared effects (the
 * objects the fighters spawn: spark, smoke, fireball-like shapes), and the pointer words of its tables.
 *
 * Effects. `spawned_object_data_a` (4,692 bytes: position runs) and `spawned_object_data_b` (12,114 bytes: 223 cell lists)
 * are, like a fighter module's blocks, the conversion of the arcade's art records (the rules are those of fighter.c and of
 * the model in fighters.py), with two differences found in `program_map.py --effects`: the PS1 leaves out some cells of a
 * record (40 of them; the PS1's art tool cleaned away the few stray pixels they held, so that their tiles were blank), and
 * 6 lists (full-screen pictures of 24 x 14 tiles drawn from art of the PS1's own) are not the arcade's. The descriptor
 * (program_effects_table.c, generated by `program_map.py --c-table effects`) names the records and the left-out cells; the
 * build says which bytes it made (`known`). Their tiles are the stage files' chunk of table 0 slot 3 (2,336 tiles).
 *
 * Relocations. The program's tables hold the addresses of functions (handler tables), of its own data and of the overlay
 * modules' load area. They are fixed by the PS1 program's layout; the table (program_relocs_table.c, generated by
 * `program_map.py --c-table relocs`) lists each location with the address it holds, and arcade_relocs_apply() writes them.
 * Only addresses are here, no byte of either game. `program_map.py --compare-c` checks both against the disc. */
#ifndef ARCADE_PROGRAM_MORE_H
#define ARCADE_PROGRAM_MORE_H

#include <stddef.h>
#include <stdint.h>
#include "fighter.h"

/* ---- effects */

/* The cells of a record that the PS1 leaves out are struct arcade_fighter_drop (fighter.h). */

struct arcade_effects {
    uint32_t address;                                    /* PS1 address of the positions; the lists follow at address + positions_size */
    uint32_t positions_size, lists_size;                 /* bytes of the two blocks */
    const struct arcade_fighter_segment *segments;       /* consecutive records made into lists, as for a fighter (address 0: empty lists) */
    unsigned segment_count;
    const struct arcade_fighter_drop *drops;
    unsigned drop_count;
    /* After the lists made from the segments come gap_size bytes of lists the build does not make (the PS1's pictures), then a
     * last empty list. The positions of those pictures are one stream of `picture_rows` rows of `picture_columns` tiles, stored
     * after the others; the empty list's position offset is the end of that stream; the positions block ends with zeros. */
    uint32_t gap_size;
    uint16_t picture_columns, picture_rows;
};

extern const struct arcade_effects arcade_effects;

struct arcade_effects_out {
    uint8_t *data;       /* positions_size bytes of positions, then lists_size bytes of lists */
    uint8_t *known;      /* known[i] = 1: data[i] was built (the gap is 0 and is the disc's) */
    uint32_t size;
};

/* Build the blocks of `e` from the arcade program (the 68000's view). 0, or -1 with a message in err (a record outside the
 * program, a cell index that is not in its record, a block that needs more than its size or that does not leave the size the
 * descriptor says); then nothing stays allocated and `out` is zeroed. Free with arcade_effects_free. */
int arcade_effects_build(const uint8_t *program, size_t program_size, const struct arcade_effects *e,
                         struct arcade_effects_out *out, char *err, size_t errsize);
void arcade_effects_free(struct arcade_effects_out *out);

/* ---- relocations */

/* The word at `location` (PS1 address, 4-byte aligned, inside the program's data) holds `target` (little-endian 32 bits). */
struct arcade_reloc {
    uint32_t location;
    uint32_t target;
};

extern const struct arcade_reloc arcade_relocs[];
extern const unsigned arcade_reloc_count;

/* Write the words into `ram`, the PS1 program's data from ARCADE_PS1_DATA_START (ram_size bytes). Words that do not fit are
 * not written and make it return -1; 0 when all were. */
int arcade_relocs_apply(const struct arcade_reloc *r, unsigned count, uint8_t *ram, size_t ram_size);
/* The table's own order and bounds: sorted by location, 4-byte aligned, inside the program's data. 0 or -1. */
int arcade_relocs_valid(const struct arcade_reloc *r, unsigned count);

#endif

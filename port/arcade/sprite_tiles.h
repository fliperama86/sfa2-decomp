/* Every tile of a fighter file's sprite chunk, from the arcade graphics (port/arcade/README.md, "Playing without the disc"). The PS1's
 * fighter tiles are arcade graphics tiles (the colour index one higher), each stored with a flip; fighter.c numbers the ones its cell
 * lists use, but a chunk also holds tile 0 and tiles after the numbered ones (used by the PS1's own steps), and the files fighter.c
 * leaves out have none numbered. This table gives, for every tile of every fighter file's chunk, its arcade tile and flip, as runs, so
 * that the runtime builds the whole chunk from the arcade set and a pack keeps none of it. A tile the arcade does not have is an OWN
 * run (none are expected; the tool reports them and the runtime then keeps the disc's chunk). Generated by sprite_tiles.py --c-table
 * (sprite_tiles_table.c): codes, flips and counts only, no byte of either game. */
#ifndef ARCADE_SPRITE_TILES_H
#define ARCADE_SPRITE_TILES_H

#include <stddef.h>
#include <stdint.h>

#define ARCADE_SPRITE_RUN_BLANK 0xfffffffeu   /* code of a run of blank tiles (all pixels 0) */
#define ARCADE_SPRITE_RUN_OWN 0xffffffffu     /* code of a run of tiles the arcade does not have */

/* Bit 2 of a run's flip: tiles where the disc has the PS1's own art (poses the arcade draws its own way), drawn as the arcade draws the
 * same cells (by the owner's rule "rebuild arcade-style"). They differ from the disc's tiles by design; the loader's check skips them. */
#define ARCADE_SPRITE_REDRAWN 4u

/* Tiles `count` from the run's place on: arcade codes code, code + step, code + 2 * step, ... each stored with flip (bit 0 across,
 * bit 1 down; bit 2 ARCADE_SPRITE_REDRAWN); step is 1, 0 (the same tile again) or -1. */
struct arcade_sprite_run {
    uint32_t code;
    uint16_t count;
    int8_t step;
    uint8_t flip;
};

struct arcade_sprite_chunk {
    const char *file;          /* "PL00.PAC" */
    uint16_t slot;             /* table 0 slot of the sprite chunk (1 first side, 2 second side) */
    uint32_t size;             /* bytes of the disc's chunk: the room the packed tiles must fit */
    uint32_t tiles;            /* tiles of the chunk (the sum of the runs' counts) */
    const struct arcade_sprite_run *runs;
    unsigned run_count;
};

extern const struct arcade_sprite_chunk arcade_sprite_chunks[];
extern const unsigned arcade_sprite_chunk_count;

const struct arcade_sprite_chunk *arcade_sprite_chunk_find(const char *file);

/* The chunk's tiles (c->tiles of 128 bytes, the PS1's 4 bits a pixel, the left pixel of a pair in the low nibble) from the arcade
 * graphics (tiles_size bytes, 128 a tile). -1 with a message when a code lies outside the graphics, a run is OWN, or the runs' counts
 * do not add up to c->tiles. */
int arcade_sprite_tiles_build(const struct arcade_sprite_chunk *c, const uint8_t *tiles, size_t tiles_size, uint8_t (*out)[128],
                              char *err, size_t errsize);

#endif

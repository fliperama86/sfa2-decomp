#!/usr/bin/env python3
"""Analysis tool: the disc's layout as numbers and names (the table that port/src/disc.c's layout backend reads).

What it does. The port's disc layer needs, of the disc's structure, only: which files there are (name, first sector, length), how the music streams'
sectors are labelled (the XA subheaders, which the drive model reads), and which sectors outside the files are not data sectors. This tool reads them
from the disc once and writes them as numbers and names (port/arcade/layout_table.c), so that a run needs no volume descriptor, no directory sector,
no raw sector outside the files and no stream subheader from the disc or from a pack:

  files     every file of the root directory and the folders one level below it, as port_disc_list gives them: name (lower case, no folder, no
            version suffix; two files of one name are refused), first sector, length in bytes; sorted by first sector;
  streams   every `.xa` file: its sector count and, for each of the 8 channels, the last sector (counted from the file's first) that holds that
            channel's sound. The subheader of sector i is then (file 1, channel, submode, coding) twice, by this model, which the tool verifies
            against every sector of every stream before it writes anything:
              i = count - 1             channel 0, submode 0x80, coding 0                      (the file's last sector)
              i <= end[i mod 8]         channel i mod 8, submode 0x64, coding 1; submode 0xe4 when i == end[i mod 8]
              otherwise                 channel 0, submode 0, coding 0                         (a place of a channel whose sound has ended)
  fills     the runs of 16 sectors or more outside the files whose sectors all have one submode other than 8 (a data sector's): first sector,
            count, submode. Any other sector outside the files is made as a form 1 data sector of zeros.

Inputs: the disc image (--disc, raw 2352-byte sectors). It writes only what --c-table names; it prints numbers and names, never game bytes.

    python3 port/arcade/layout.py --disc BIN [--c-table FILE]       # report; with --c-table also write port/arcade/layout_table.c
    python3 port/arcade/layout.py --disc BIN --check                # the checked-in table is the one the disc gives now
"""
import argparse
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / 'ps1/tools'))

SECTOR, DATA = 2352, 2048
MIN_FILL = 16
DATA_SUBMODE = 8


class Fail(Exception):
    pass


def clean_name(path):
    """The name port_disc_list gives a file: the last component, lower case, no ';1' version suffix, no trailing dot."""
    name = path.rsplit('/', 1)[-1].split(';')[0]
    return name.rstrip('.').lower()


def model_subheader(count, end, i):
    """The 8 bytes of the subheader of sector i of a stream of `count` sectors whose channel c has its last sound sector at end[c]."""
    if i == count - 1:
        chan, sub, coding = 0, 0x80, 0
    elif i <= end[i % 8]:
        chan, sub, coding = i % 8, (0xe4 if i == end[i % 8] else 0x64), 1
    else:
        chan, sub, coding = 0, 0, 0
    one = bytes([1, chan, sub, coding])
    return one + one


def stream_ends(subheaders):
    """The 8 channel ends of a stream from its sectors' subheaders (the 8 bytes each), or raise Fail when the model does not reproduce them."""
    count = len(subheaders)
    end = [None] * 8
    for i, s in enumerate(subheaders):
        if s[2] == 0xe4:
            if end[s[1]] is not None or i % 8 != s[1]:
                raise Fail(f'channel {s[1]} ends twice or at a place that is not its own (sector {i})')
            end[s[1]] = i
    if None in end:
        raise Fail('a channel of the stream has no last sound sector')
    for i, s in enumerate(subheaders):
        if bytes(s) != model_subheader(count, end, i):
            raise Fail(f'sector {i} of the stream is not what the model gives: {bytes(s).hex()} against {model_subheader(count, end, i).hex()}')
    return end


def fill_runs(headers, covered):
    """[(first, count, submode)] of the runs of MIN_FILL or more sectors outside the files (covered[i] false) whose sectors all have the same
    (file, channel, submode, coding) and a submode other than DATA_SUBMODE. headers[i] = bytes 16..24 of sector i."""
    runs, i, n = [], 0, len(headers)
    while i < n:
        if covered[i]:
            i += 1
            continue
        j = i
        while j < n and not covered[j] and headers[j][:4] == headers[i][:4]:
            j += 1
        if j - i >= MIN_FILL and headers[i][2] != DATA_SUBMODE:
            runs.append((i, j - i, headers[i][2]))
        i = j
    return runs


def c_table(sectors, files, streams, fills):
    lines = ['/* Generated by port/arcade/layout.py --c-table; names and numbers only. The disc\'s layout: its files, the labels of its music',
             ' * streams\' sectors and the runs of sectors outside the files that are not data sectors (port/src/port.h, "The disc\'s layout"). */',
             '#include "port.h"', '',
             'static const struct port_layout_file layout_files[] = {']
    for name, sector, size in files:
        lines.append(f'    {{"{name}", {sector}, {size}}},')
    lines += ['};', '', 'static const struct port_layout_stream layout_streams[] = {']
    for first, count, end in streams:
        lines.append(f'    {{{first}, {count}, {{' + ', '.join(str(e) for e in end) + '}},')
    lines += ['};', '', 'static const struct port_layout_fill layout_fills[] = {']
    for first, count, sub in fills:
        lines.append(f'    {{{first}, {count}, 0x{sub:02x}}},')
    lines += ['};', '',
              'static const struct port_layout arcade_layout = {',
              f'    {sectors}, layout_files, {len(files)}, layout_streams, {len(streams)}, layout_fills, {len(fills)}',
              '};', '',
              'const struct port_layout *port_arcade_layout(void)', '{', '    return &arcade_layout;', '}', '']
    return '\n'.join(lines)


def read_layout(disc_path):
    import fighters
    with open(disc_path, 'rb') as f:
        files, sec = fighters.iso_files(f)
        f.seek(0, 2)
        sectors = f.tell() // SECTOR
        named, seen = [], {}
        for path, (lba, size) in files.items():
            name = clean_name(path)
            if name in seen:
                raise Fail(f'two files are named {name}')
            seen[name] = path
            named.append((name, lba, size))
        named.sort(key=lambda x: x[1])
        covered = bytearray(sectors)
        for name, lba, size in named:
            for k in range((size + DATA - 1) // DATA):
                if lba + k < sectors:
                    covered[lba + k] = 1
        streams = []
        for name, lba, size in named:
            if not name.endswith('.xa'):
                continue
            count = (size + DATA - 1) // DATA
            f.seek(lba * SECTOR)
            blob = f.read(count * SECTOR)
            subs = [blob[k * SECTOR + 16:k * SECTOR + 24] for k in range(count)]
            try:
                end = stream_ends(subs)
            except Fail as e:
                raise Fail(f'{name}: {e}')
            streams.append((lba, count, end))
        headers = []
        for i in range(sectors):
            if covered[i]:
                headers.append(b'\0' * 8)
                continue
            f.seek(i * SECTOR + 16)
            headers.append(f.read(8))
        fills = fill_runs(headers, covered)
    return sectors, named, streams, fills


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--disc', required=True)
    ap.add_argument('--c-table')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    try:
        sectors, files, streams, fills = read_layout(a.disc)
    except Fail as e:
        print(f'FAIL: {e}')
        return 1
    text = c_table(sectors, files, streams, fills)
    print(f'{sectors} sectors; {len(files)} files; {len(streams)} streams ({sum(c for _, c, _ in streams)} sectors, model verified on every sector); '
          f'{len(fills)} fill runs ({", ".join(f"{c} at {f} submode 0x{s:02x}" for f, c, s in fills)})')
    if a.c_table:
        Path(a.c_table).write_text(text)
        print(f'wrote {a.c_table}')
    if a.check:
        same = (HERE / 'layout_table.c').exists() and (HERE / 'layout_table.c').read_text() == text
        print('checked-in layout_table.c ' + ('equals' if same else 'DIFFERS FROM') + ' the table this tool derives')
        return 0 if same else 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
